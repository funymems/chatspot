import { Cpu, FlaskConical } from "lucide-react";
import type { AiStatus } from "@/lib/server/ai/provider";

/** Tells the user honestly which engine answers: Gemini or the built-in demo mode. */
export function AiStatusBanner({ status }: { status: AiStatus }) {
  if (status.mode === "live") {
    return (
      <p className="flex items-center gap-2 rounded-lg border bg-card px-3 py-2 text-xs text-muted-foreground">
        <Cpu className="size-4 text-primary" aria-hidden />
        Replies are generated by <span className="font-medium text-foreground">{status.provider}</span> ({status.model}) using only each agent&apos;s
        knowledge base.
      </p>
    );
  }
  return (
    <p className="flex items-start gap-2 rounded-lg border border-warning/40 bg-warning/10 px-3 py-2 text-xs text-amber-800">
      <FlaskConical className="mt-px size-4 shrink-0" aria-hidden />
      <span>
        <span className="font-medium">Demo mode.</span> No AI provider is configured, so agents answer with the best-matching knowledge entry
        (no language model). Add <code className="rounded bg-amber-100 px-1">GEMINI_API_KEY</code> to <code className="rounded bg-amber-100 px-1">.env.local</code> and restart to use Gemini.
      </span>
    </p>
  );
}
